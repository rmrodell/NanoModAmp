#!/usr/bin/env Rscript
# Write containers/nanomodamp-r/r-packages.tsv: the exact R package versions of the Sherlock
# reference environment (R 4.3.2 module + ~/R/x86_64-pc-linux-gnu-library/4.3) that the WP3/WP4
# tests and the test-11 legacy references were produced with.
#
# Roots: nanomodamp DESCRIPTION Imports, the test/CLI packages, and the packages the vendored
# legacy scripts (dev/legacy, dev/published: modification_analysis.R, incell_analysis.R,
# bam_counts*.R) load. The closure follows Depends/Imports/LinkingTo. Base packages are dropped;
# packages whose copy in use is the one shipped with R (.Library) get repository "R": the image
# build does not install them but asserts their version.
# Rows are in install order (dependencies first).
#
# Usage (Sherlock):  unset R_HOME; module load R/4.3.2
#   /share/software/user/open/R/4.3.2/bin/Rscript containers/nanomodamp-r/make_lockfile.R [repo_root]

args <- commandArgs(trailingOnly = TRUE)
root <- if (length(args)) args[1] else "."
desc <- read.dcf(file.path(root, "R/nanomodamp/DESCRIPTION"), fields = "Imports")[1, 1]
imports <- trimws(sub("\\(.*", "", strsplit(desc, ",")[[1]]))
extra <- c("testthat", "optparse", "argparse", "furrr", "readr", "forcats", "purrr", "ggtext",
           "future.callr", "GenomicAlignments")
roots <- setdiff(unique(c(imports, extra)), "")

ip <- installed.packages(fields = c("Repository", "biocViews", "git_url"))
ip <- ip[!duplicated(ip[, "Package"]), , drop = FALSE]   # first libPath wins, as library() does
rownames(ip) <- ip[, "Package"]

deps <- tools::package_dependencies(roots, db = ip, which = c("Depends", "Imports", "LinkingTo"),
                                    recursive = TRUE)
closure <- intersect(unique(c(roots, unlist(deps))), rownames(ip))
missing <- setdiff(roots, rownames(ip))
if (length(missing)) stop("not installed on this system: ", paste(missing, collapse = ", "))

keep <- vapply(closure, function(p) {
  prio <- ip[p, "Priority"]
  if (!is.na(prio) && prio == "base") return(FALSE)
  TRUE
}, logical(1))
pkgs <- closure[keep]

direct <- tools::package_dependencies(pkgs, db = ip, which = c("Depends", "Imports", "LinkingTo"))
ordered <- character()
while (length(ordered) < length(pkgs)) {
  ready <- setdiff(pkgs[vapply(pkgs, function(p) all(intersect(direct[[p]], pkgs) %in% ordered),
                               logical(1))], ordered)
  if (!length(ready)) stop("dependency cycle among: ", paste(setdiff(pkgs, ordered), collapse = ", "))
  ordered <- c(ordered, sort(ready))
}

repo <- vapply(ordered, function(p) {
  # recommended packages shipped with R: not installed, but the build asserts their version
  if (normalizePath(ip[p, "LibPath"]) == normalizePath(.Library)) return("R")
  if (identical(unname(ip[p, "Repository"]), "CRAN")) return("CRAN")
  if (!is.na(ip[p, "git_url"]) && grepl("bioconductor", ip[p, "git_url"])) return("Bioconductor")
  if (!is.na(ip[p, "biocViews"])) return("Bioconductor")   # e.g. GenomeInfoDbData (data/annotation repo)
  "UNKNOWN"
}, character(1))
if (any(repo == "UNKNOWN")) warning("unknown source: ", paste(ordered[repo == "UNKNOWN"], collapse = ", "))
out <- data.frame(package = ordered, version = ip[ordered, "Version"], repository = repo)
f <- file.path(root, "containers/nanomodamp-r/r-packages.tsv")
writeLines(c(sprintf("# generated by make_lockfile.R on %s from R %s (%s)", Sys.Date(),
                     getRversion(), paste(.libPaths(), collapse = ":")),
             "package\tversion\trepository",
             paste(out$package, out$version, out$repository, sep = "\t")), f)
cat(nrow(out), "packages written to", f, "\n")
